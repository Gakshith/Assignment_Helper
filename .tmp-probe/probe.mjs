import { parse } from 'opentype.js/dist/opentype.mjs';
import { readFileSync } from 'node:fs';
const buf = readFileSync('spikes/m0/fonts/Caveat-Regular.ttf');
const f = parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const probe = [0xb5,0x2212,0x2044,0x2215,0xd7,0xf7,0xb1,0x2264,0x2265,0x2260,0x2248,0xb0,0xb7,0x2022,0x2032,0x2033,0x2261,0x7c,0x2a,0x27,0x22,0x2d,0x20,0xa0,0x2026,0x2013,0x2014,0x5e,0x7e,0x5f,0x3c,0x3e,0x28,0x29,0x5b,0x5d,0x7b,0x7d,0x2192];
for (const cp of probe) {
  const c = String.fromCodePoint(cp);
  const has = f.hasChar(c);
  const g = has ? f.charToGlyph(c) : null;
  console.log('U+' + cp.toString(16).padStart(4, '0'), JSON.stringify(c), has, g ? g.index : '-', g ? g.name : '-');
}
